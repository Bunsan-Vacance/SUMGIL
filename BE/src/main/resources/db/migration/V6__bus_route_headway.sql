-- V6: bus_route 에 배차간격 열 추가 (S15P21A104-228).
--
-- 경로 탐색이 버스 대기시간을 계산할 근거가 없어 지금은 BusEdgeBuilder 가 모든 BUS 엣지의 waitSec 을 0 으로 둔다.
-- 지하철은 edge_time 에 요일·슬롯별 wait_sec 이 채워져 있는데 버스만 비어 있었다.
-- 그래프가 이 값을 읽어 wait_sec = headway_min * 60 / 2 로 쓰는 것은 A 파트 후속이고, 여기서는 표만 채운다.
--
-- edge_time 이 아니라 bus_route 에 두는 이유: 배차간격은 노선 속성이고 시간대별로 갈리지 않는다.
-- 원천(도착정보 API 의 term)이 노선당 값 하나이며, 2026-09-08 11:10 과 09-17 14:59 두 관측에서
-- 14개 노선 전부 값이 같았다. edge_time BUS 행으로 만들면 41,688 구간 x 요일 3 x 슬롯 48 = 약 600만 행에
-- 같은 값이 복제된다.
--
-- NULL 을 허용한다. 원천이 0 을 주는 경우가 있는데 "배차 0분" 이 아니라 "그 시각에 운행 중이 아니라 모른다" 는 뜻이다.
-- 0 을 그대로 넣으면 대기시간이 0초가 되어 그 노선이 무조건 최단 경로로 뽑힌다.
-- 2026-09-17 수집 기준 718 노선 중 446 개만 값이 있다 — 나머지는 도착정보 API 가 다루지 않는 노선이다
-- (마을버스 상당수. 근거는 BE/docs/db/load-bus-bike.md "배차간격").
--
-- 첫차·막차는 이 마이그레이션에 넣지 않았다. 같은 API 응답에 있지만 9일 사이 12/14 노선이 몇 분씩 달라져
-- 정적 표에 넣으면 낡는다. 수집 CSV 에는 남아 있으므로 쓰기로 정하면 그때 열을 추가한다.
ALTER TABLE bus_route ADD COLUMN headway_min INTEGER;

COMMENT ON COLUMN bus_route.headway_min IS
  '배차간격(분). 노선당 대표값 하나이며 시간대별로 갈리지 않는다. NULL 은 원천이 값을 주지 않은 노선 — 주로 도착정보 API 가 다루지 않는 마을버스';
